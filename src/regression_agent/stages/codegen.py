"""Stage 6: code generation.

One pytest file per test spec. Every method name is copied verbatim from
skill_endpoint_map.json and every request is validated against grpc_spec.json
first, so generated code can't call something that doesn't exist. Code
generation is deterministic: the reviewed spec is exactly what runs.
"""
from __future__ import annotations

import re
import textwrap

from ..workspace import Workspace
from .design import validate

CONFTEST = '''"""Generated by ai-regression-agent. Shared fixture for all generated tests."""
import os

import pytest

from regression_agent.runtime import Harness


def pytest_configure(config):
    config.addinivalue_line("markers", "e2e(id, requirements): generated end-to-end test")


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    if rep.when == "call":
        item.rga_report = rep


@pytest.fixture
def rga(request):
    marker = request.node.get_closest_marker("e2e")
    harness = Harness(
        target=os.environ["RGA_TARGET"],
        proto=os.environ["RGA_PROTO"],
        evidence_dir=os.environ.get("RGA_EVIDENCE_DIR", "test_logs"),
        reset_rpc=os.environ.get("RGA_RESET_RPC") or None,
    )
    harness.test_id = marker.kwargs["id"] if marker else request.node.name
    harness.meta = {"requirements": marker.kwargs.get("requirements", []) if marker else [],
                    "nodeid": request.node.nodeid}
    harness.reset()
    yield harness
    rep = getattr(request.node, "rga_report", None)
    outcome = "passed" if rep is not None and rep.passed else "failed"
    harness.write_evidence(outcome, str(rep.longrepr)[-2000:] if rep is not None and rep.failed else None)
'''


def slug(text: str, n: int = 6) -> str:
    words = re.findall(r"[a-z0-9]+", text.lower().split(":", 1)[-1])
    return "_".join(words[:n]) or "scenario"


def file_name(test: dict) -> str:
    return f"test_{test['id'].lower().replace('-', '_')}_{slug(test['title'])}.py"


def render(test: dict) -> str:
    fn = f"test_{test['id'].lower().replace('-', '_')}_{slug(test['title'], 5)}"
    doc = textwrap.fill(f"{test['id']}: {test['title']}", 100)
    lines = [
        f'"""{doc}',
        "",
        f"Verifies: {', '.join(test['requirements'])}",
        f"Skills: {', '.join(test['skills'])}",
        f"Confidence: {test['confidence']}/100",
        "",
        "Generated by ai-regression-agent from e2e_tests.json. Don't edit by hand: change the spec and",
        "regenerate, so the test and its traceability stay in sync.",
        '"""',
        "import pytest",
        "",
        "",
        f"@pytest.mark.e2e(id={test['id']!r}, requirements={test['requirements']!r})",
        f"def {fn}(rga):",
    ]
    for i, st in enumerate(test["steps"], start=1):
        args = [str(i), repr(st["skill"]), repr(st["method"]), repr(st["request"])]
        exp = st.get("expect") or {}
        if exp.get("code", "OK") != "OK":
            args.append(f"expect_code={exp['code']!r}")
        if exp.get("fields"):
            args.append(f"expect_fields={exp['fields']!r}")
        if st.get("save_as"):
            args.append(f"save_as={st['save_as']!r}")
        lines.append(f"    # step {i}: {st['skill']}")
        call = f"    rga.call({', '.join(args)})"
        if len(call) > 110:
            call = "    rga.call(\n        " + ",\n        ".join(args) + ",\n    )"
        lines.append(call)
    return "\n".join(lines) + "\n"


def generate(ws: Workspace, tests: list[dict], only: set[str] | None = None) -> dict:
    spec = ws.read_json("grpc_spec.json")
    mapping = ws.read_json("skill_endpoint_map.json")
    ws.tests_dir.mkdir(parents=True, exist_ok=True)
    (ws.tests_dir / "conftest.py").write_text(CONFTEST)
    (ws.tests_dir / "__init__.py").write_text("")
    written, rejected = [], []
    for t in tests:
        if only is not None and t["id"] not in only:
            continue
        errors = validate(t, spec, mapping)
        if errors:
            rejected.append({"id": t["id"], "errors": errors})
            continue
        for old in ws.tests_dir.glob(f"test_{t['id'].lower().replace('-', '_')}_*.py"):
            old.unlink()
        name = file_name(t)
        (ws.tests_dir / name).write_text(render(t))
        t["file"] = f"tests/generated/{name}"
        written.append(name)
    return {"written": written, "rejected": rejected}


def run(ws: Workspace) -> dict:
    tests = ws.read_json("e2e_tests.json")
    for f in ws.tests_dir.glob("test_e2e_*.py"):
        f.unlink()  # full run: regenerate everything from the approved specs
    result = generate(ws, tests)
    ws.write_json("e2e_tests.json", tests)  # now with file paths
    ws.write_json("codegen_report.json", result)
    return {"files": len(result["written"]), "rejected": len(result["rejected"])}
